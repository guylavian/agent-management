import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

/**
 * Fails the build if git is tracking something it should never track.
 *
 * This exists because the same mistake happened three times during the layout
 * migrations, and each time it was caught by eye rather than by a check:
 *
 *   - `deploy/local/keycloak/certs/tls.key`, twice — a private key, tracked
 *     because an ignore rule NAMED a path and a `git mv` moved the tree out
 *     from under it
 *   - `agent-engine/node_modules`, 4,939 files — a new repository-root sibling
 *     with no .gitignore of its own
 *   - `deploy/local/.real-poc/…/keycloakdb.mv.db` — the Keycloak database,
 *     holding every agent's client secret, written where no rule reached
 *
 * Ignore rules describe where things are. This describes what things ARE, so
 * moving a directory cannot silently disarm it.
 */

interface Rule {
  what: string;
  why: string;
  matches: (path: string) => boolean;
}

const RULES: Rule[] = [
  {
    what: "private key or certificate material",
    why: "credentials never belong in Git, and local TLS material is generated by tools/gen-keycloak-cert.sh",
    matches: (path) => /\.(pem|key|p12|pfx|jks)$/u.test(path) || /\/certs?\//u.test(path),
  },
  {
    what: "an installed dependency tree",
    why: "node_modules is reproducible from the lockfile",
    matches: (path) => path.split("/").includes("node_modules"),
  },
  {
    what: "local PoC or runtime state",
    why: "derived state rebuilt by tools/prepare-real-poc.sh; it also carries Keycloak's database and generated keys",
    matches: (path) => path.split("/").includes(".real-poc") || /\.(mv|trace)\.db$/u.test(path),
  },
  {
    what: "a real environment file",
    why: "only .example templates are committed",
    matches: (path) => /(^|\/)\.env(\.[a-z-]+)?$/u.test(path) && !path.endsWith(".example"),
  },
  {
    what: "build or run output",
    why: "produced by a build or a run, not authored",
    matches: (path) => /(^|\/)(dist|coverage|results)\//u.test(path),
  },
  {
    what: "an archive",
    why: "source archives are produced on demand and belong outside the repository",
    matches: (path) => /\.(zip|tar|tgz|tar\.gz|7z|rar)$/u.test(path),
  },
];

/** Content that is a secret regardless of where it sits or what it is called. */
const SECRET_CONTENT = /-----BEGIN (?:RSA |EC |OPENSSH |ENCRYPTED )?PRIVATE KEY-----/u;

// the repository root, not the workspace root: this checks the whole repository
const tracked = execFileSync("git", ["ls-files"], { cwd: "..", encoding: "utf8" })
  .split("\n")
  .filter(Boolean);

const violations: string[] = [];
for (const path of tracked) {
  for (const rule of RULES) {
    if (rule.matches(path)) violations.push(`${path}\n    tracked ${rule.what} — ${rule.why}`);
  }
}

// a file can pass every name-shaped rule and still contain a key
for (const path of tracked) {
  if (!/\.(md|json|ya?ml|ts|tsx|js|sh|txt|lock)$/u.test(path)) continue;
  try {
    if (SECRET_CONTENT.test(readFileSync(`../${path}`, "utf8"))) {
      violations.push(`${path}\n    contains PEM private key material`);
    }
  } catch {
    // unreadable or binary; the name-shaped rules above already cover those
  }
}

if (violations.length > 0) {
  console.error(`git is tracking ${violations.length} file(s) it must not:\n`);
  for (const violation of violations) console.error(`  ${violation}`);
  console.error("\nUntrack with `git rm --cached`, then add a rule to the .gitignore of the subtree that owns it.");
  process.exit(1);
}

console.log(`tracked-file policy ok — ${tracked.length} files, no credentials, dependencies or local state`);
