import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import express from "express";
import { CONFIG_PATHS, loadAppConfig } from "@sre/config";
import {
  desiredStateSource,
  effectiveCatalog,
  ProbeAvailabilityMonitor,
  managementRouter,
  InMemoryRunStore,
  unobserved,
  type AgentReconciliation,
  type DeploymentStatusSource,
  type RuntimeProbe,
  type Signal,
} from "@sre/runtime-host";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

/**
 * MERGE IS ENOUGH.
 *
 * The failure this file exists to prevent: an operator creates an Agent, the
 * pull request merges, and nothing happens. The Agent was in Git, Argo had
 * synced it, the pod was healthy — and the console listed the world as it had
 * been when the Manager process last booted, while the Manager itself was never
 * offered the Agent because a hand-written `agents.allowed` list in a THIRD
 * file had not been edited. Three separate silent gates, none of which reported
 * anything.
 *
 * Every test below runs against ONE router over ONE desired-state source, held
 * for the whole file. Nothing is rebuilt between steps, so a test that passes
 * proves the state changed without a restart — of the runtime or of the portal.
 *
 * No agent id here is written into product code. The name is generated, so a
 * test that only passed for the agents that happen to be checked in would fail.
 */

const NEW_AGENT = `probe-${Math.random().toString(36).slice(2, 8)}`;
const ENVIRONMENT = "onboarding-test";

let repo: string;
let source: ReturnType<typeof desiredStateSource>;
let catalog: ReturnType<typeof effectiveCatalog>;
let monitor: ProbeAvailabilityMonitor;
let app: express.Express;
let clock = Date.UTC(2026, 0, 1);
/** the fake Argo/pod, so the reconciliation sequence is observable at all */
let argoSignal: Signal = unobserved("not asked yet");
let runtimeSignal: Signal = unobserved("not asked yet");

const argo: DeploymentStatusSource = { status: async () => argoSignal };
const probe: RuntimeProbe = { status: async () => runtimeSignal };

/**
 * Advance past the revalidation window and take one availability sweep, which
 * is what the passage of wall-clock time does in a running process. The sweep
 * is driven explicitly rather than by a timer so these assertions are about the
 * state machine and not about how fast the test host happens to be.
 */
async function tick(): Promise<void> {
  clock += 60_000;
  await monitor.sweep();
}

function deployDir(): string {
  return join(repo, "deploy", "environments", ENVIRONMENT);
}

/** Write the two files a merged "create agent" pull request leaves behind. */
function mergeAgent(name: string, options: { enabled: boolean; lifecycle?: "active" | "draft" }): void {
  writeFileSync(join(repo, CONFIG_PATHS.agentsDir, `${name}.yaml`), agentDocument(name, options.lifecycle ?? "active"), "utf8");
  writeFileSync(join(repo, CONFIG_PATHS.promptsDir, `${name}.md`), `# ${name}\n\nInvestigate within your domain.\n`, "utf8");
  mergeOverlay(name, options.enabled);
}

function mergeOverlay(name: string, enabled: boolean): void {
  writeFileSync(
    join(deployDir(), "agents", `${name}.yaml`),
    ["apiVersion: sre.ai/v1alpha1", "kind: AgentDeployment", `agentId: ${name}`, `enabled: ${enabled}`, "replicas: 2", ""].join("\n"),
    "utf8",
  );
}

function agentDocument(name: string, lifecycle: "active" | "draft" = "active"): string {
  return [
    "apiVersion: sre.ai/v1alpha1",
    "kind: Agent",
    "metadata:",
    `  name: ${name}`,
    "  owner: sre-platform",
    `  description: "generated by the onboarding test"`,
    "spec:",
    "  type: specialist",
    `  lifecycle: ${lifecycle}`,
    "  model: { tier: small, profile: tool-caller }",
    `  prompt: { systemFile: config/prompts/${name}.md }`,
    `  identity: { provider: keycloak, clientId: sre-agent-${name} }`,
    '  environments: ["prod"]',
    "  routing:",
    '    capabilities: ["a generated capability"]',
    "    exclusions: []",
    "  access:",
    "    - mcp: wiki",
    "      audience: sre-toolhive:wiki",
    "      tools: [wiki_search]",
    "  execution: { maxToolCalls: 6, maxModelTurns: 6, timeoutMs: 120000, maxEvidenceBytes: 262144, maxContextTokens: 12000, maxEvidenceItems: 32, maxRawExcerptBytes: 8192 }",
    "  authorization: { requiredRoles: [infra-read] }",
    "  security: { readOnly: true }",
    "",
  ].join("\n");
}

interface ListedAgent {
  id: string;
  reconciliation?: AgentReconciliation;
}

describe("a merged Agent appears, reconciles and becomes routable with no restart", () => {
  beforeAll(async () => {
    repo = mkdtempSync(join(tmpdir(), "sre-onboarding-"));
    // a real repository layout, copied rather than mocked: the loaders, the
    // schemas and the semantic validation are the ones the runtime runs
    cpSync(join(process.cwd(), "config"), join(repo, "config"), { recursive: true });
    mkdirSync(join(deployDir(), "agents"), { recursive: true });
    writeFileSync(
      join(deployDir(), "environment.yaml"),
      ["apiVersion: sre.ai/v1alpha1", "kind: DeploymentEnvironment", `environment: ${ENVIRONMENT}`, "namespace: sre-assistant", ""].join("\n"),
      "utf8",
    );
    writeFileSync(
      join(deployDir(), "manager.yaml"),
      ["apiVersion: sre.ai/v1alpha1", "kind: AgentDeployment", "agentId: manager", "enabled: true", "replicas: 2", ""].join("\n"),
      "utf8",
    );
    // every checked-in specialist enabled, so the baseline is a working platform
    for (const file of ["active-directory", "keycloak", "network-observability", "observability", "openshift"]) {
      mergeOverlay(file, true);
    }

    source = desiredStateSource(
      { ...CONFIG_PATHS, baseDir: repo, deploymentEnvironmentDir: join(repo, "deploy", "environments", ENVIRONMENT), revalidateMs: 5_000 },
      { now: () => clock },
    );
    // the REAL wiring: the catalog the Manager routes from is desired state
    // intersected with what the probe has observed, and the management API is
    // handed that same object rather than a second derivation of it
    monitor = new ProbeAvailabilityMonitor(probe, () => source.current().catalog.listEnabled());
    catalog = effectiveCatalog(source, monitor);

    app = express();
    app.use(
      "/management",
      managementRouter({
        state: () => ({ ...source.current(), catalog, enabledAgentIds: catalog.listEnabled().map(entry => entry.agentId) }),
        config: loadAppConfig({ SRE_ENV: "local" }),
        runs: new InMemoryRunStore(),
        argo,
        runtimeProbe: probe,
      }),
    );
    await monitor.sweep();
  });

  afterAll(() => {
    rmSync(repo, { recursive: true, force: true });
  });

  it("does not list an Agent that has not merged", async () => {
    const before = await get("/management/agents");
    expect(before.agents.map(agent => agent.id)).not.toContain(NEW_AGENT);
  });

  it("lists a merged DRAFT as draft, which is not the same as disabled", async () => {
    // desired state read like any other: the document is in Git, and it says
    // this Agent is not meant to run yet. Nothing was turned off, so nobody
    // should be sent looking for what broke.
    mergeAgent(NEW_AGENT, { enabled: true, lifecycle: "draft" });
    argoSignal = unobserved("nothing is deployed for a draft");
    runtimeSignal = unobserved("nothing is running for a draft");
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    expect(agent?.reconciliation?.status).toBe("draft");
    expect(agent?.reconciliation?.git.detail).toMatch(/draft/u);
    // and a draft is never routable, whatever the deployment overlay says
    expect(agent?.reconciliation?.manager.state).not.toBe("ok");
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).not.toContain(NEW_AGENT);
  });

  it("lists it as RECONCILING once the pull request merges, with no restart", async () => {
    mergeAgent(NEW_AGENT, { enabled: true });
    // Argo has not generated the Application yet and the pod is not up. That is
    // the normal first second of every onboarding, and it must not read as a
    // failure — every successful create would otherwise flash red.
    argoSignal = { state: "pending", detail: "no Argo CD Application yet" };
    runtimeSignal = { state: "degraded", detail: "the pod did not answer /health/ready" };
    await tick();

    const listed = await get("/management/agents");
    const agent = listed.agents.find(item => item.id === NEW_AGENT);
    expect(agent).toBeDefined();
    expect(agent?.reconciliation?.status).toBe("reconciling");
    // desired state is unambiguous even while actual state is not
    expect(agent?.reconciliation?.git.state).toBe("ok");
  });

  it("becomes ACTIVE when Argo has synced and the pod answers", async () => {
    argoSignal = { state: "ok", detail: "sync Synced, health Healthy" };
    runtimeSignal = { state: "ok", detail: "the pod answered /health/ready" };
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    expect(agent?.reconciliation?.status).toBe("active");
    expect(agent?.reconciliation?.manager.state).toBe("ok");
  });

  it("is in the Manager's routing catalog without manager.yaml being touched", async () => {
    // the assertion that used to require a second pull request
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).toContain(NEW_AGENT);
    const manager = (await get("/management/manager")) as unknown as { routable: string[]; environment: string };
    expect(manager.routable).toContain(NEW_AGENT);

    const managerDocument = readFileSync(join(repo, CONFIG_PATHS.agentsDir, "manager.yaml"), "utf8");
    // nothing in this flow wrote to it, and there is no list in it to write to
    expect(managerDocument).toBe(readFileSync(join(process.cwd(), CONFIG_PATHS.agentsDir, "manager.yaml"), "utf8"));
    expect(managerDocument).not.toMatch(/allowed/u);
  });

  it("drops out of the Manager's catalog when the pod stops answering, even though Git still enables it", async () => {
    // desired state is unchanged and still says "run this". Availability is a
    // different question, and the Manager used to be offered the first while
    // needing the second: it routed on merit, failed at fan-out, and the user
    // got a degraded answer instead of an answer from an agent that worked.
    argoSignal = { state: "ok", detail: "sync Synced, health Healthy" };
    runtimeSignal = { state: "degraded", detail: "the pod did not answer /health/ready" };
    await tick();

    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).not.toContain(NEW_AGENT);
    // and the authoritative pre-dispatch gate agrees with what was offered
    expect(catalog.filterAuthorized([NEW_AGENT], ["infra-read"], "prod")).toEqual([]);

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    expect(agent?.reconciliation?.manager.state).not.toBe("ok");
    // the console's "not routable" says WHY, and the reason is the observation
    expect(agent?.reconciliation?.manager.detail).toContain("did not answer");
  });

  it("routes to it again as soon as the pod recovers, with nothing in Git changing", async () => {
    runtimeSignal = { state: "ok", detail: "the pod answered /health/ready" };
    await tick();
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).toContain(NEW_AGENT);
    expect(catalog.filterAuthorized([NEW_AGENT], ["infra-read"], "prod")).toEqual([NEW_AGENT]);
  });

  it("stays VISIBLE and DEGRADED when the deployment fails", async () => {
    argoSignal = { state: "degraded", detail: "sync Synced, health Degraded" };
    runtimeSignal = { state: "degraded", detail: "the pod did not answer /health/ready" };
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    // the whole point: a broken agent must be findable, not absent
    expect(agent).toBeDefined();
    expect(agent?.reconciliation?.status).toBe("degraded");
    expect(agent?.reconciliation?.argo.detail).toContain("Degraded");
    expect(agent?.reconciliation?.git.state).toBe("ok");
  });

  it("treats a disable as a RECONCILIATION while Argo still holds the workload", async () => {
    mergeOverlay(NEW_AGENT, false);
    // Argo has not pruned the Application yet, so the pod may still be serving.
    // Reporting DISABLED here would tell an operator the workload is gone while
    // it is still up, which is the one wrong answer that matters in this step.
    argoSignal = { state: "ok", detail: "sync Synced, health Healthy" };
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    expect(agent?.reconciliation?.status).toBe("reconciling");
    // routability is NOT deferred though: desired state says no, so the Manager
    // stops being offered it immediately rather than when the prune completes
    expect(agent?.reconciliation?.manager.state).not.toBe("ok");
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).not.toContain(NEW_AGENT);
  });

  it("reaches DISABLED once Argo reports the workload gone", async () => {
    argoSignal = { state: "degraded", detail: "sync Synced, health Missing" };
    runtimeSignal = { state: "degraded", detail: "the pod did not answer /health/ready" };
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    // DISABLED outranks the failing probes: an agent turned off on purpose is
    // not a degraded agent, and reporting it as one trains people to ignore
    // the word
    expect(agent?.reconciliation?.status).toBe("disabled");
    expect(agent).toBeDefined();
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).not.toContain(NEW_AGENT);
  });

  it("returns to the routing catalog when it is re-enabled and ready again", async () => {
    mergeOverlay(NEW_AGENT, true);
    argoSignal = { state: "ok", detail: "sync Synced, health Healthy" };
    runtimeSignal = { state: "ok", detail: "the pod answered /health/ready" };
    await tick();

    const agent = (await get("/management/agents")).agents.find(item => item.id === NEW_AGENT);
    expect(agent?.reconciliation?.status).toBe("active");
    expect(catalog.listEnabled("prod").map(entry => entry.agentId)).toContain(NEW_AGENT);
  });

  it("reports a broken merge as FAILED and keeps serving the last good state", async () => {
    const good = readFileSync(join(repo, CONFIG_PATHS.agentsDir, `${NEW_AGENT}.yaml`), "utf8");
    writeFileSync(join(repo, CONFIG_PATHS.agentsDir, `${NEW_AGENT}.yaml`), "apiVersion: sre.ai/v1alpha1\nkind: Agent\nspec: {}\n", "utf8");
    await tick();

    const listed = await get("/management/agents");
    expect(listed.configError).toBeDefined();
    // refusing to serve because a NEW file is malformed would take a working
    // platform down over a change to one agent; the error is reported instead
    expect(listed.agents.length).toBeGreaterThan(0);
    expect(listed.agents.every(agent => agent.reconciliation?.status === "failed")).toBe(true);

    writeFileSync(join(repo, CONFIG_PATHS.agentsDir, `${NEW_AGENT}.yaml`), good, "utf8");
    await tick();
    expect((await get("/management/agents")).configError).toBeUndefined();
  });

  it("changes its revision only when a desired-state file changes", async () => {
    const first = (await get("/management/agents")).revision;
    await tick();
    // no file written: a poll must not look like a change, or a client that
    // revalidates on the revision would refetch forever
    expect((await get("/management/agents")).revision).toBe(first);
    mergeOverlay(NEW_AGENT, true);
    writeFileSync(join(deployDir(), "agents", `${NEW_AGENT}.yaml`), `${readFileSync(join(deployDir(), "agents", `${NEW_AGENT}.yaml`), "utf8")}# touched\n`, "utf8");
    await tick();
    expect((await get("/management/agents")).revision).not.toBe(first);
  });
});

/**
 * One in-process request against the router. `light-my-request` is already the
 * repository's socketless injector, so the routes are exercised through Express
 * exactly as the runtime mounts them.
 */
async function get(url: string): Promise<{ agents: ListedAgent[]; revision: string; configError?: string }> {
  const { inject } = await import("light-my-request");
  const response = await inject(app as never, { method: "GET", url });
  return response.json() as { agents: ListedAgent[]; revision: string; configError?: string };
}
