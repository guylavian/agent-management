import { CONFIG_PATHS, loadAgentRegistry } from "@sre/config";
import { HttpKeycloakAdmin, desiredClientsFor, reconcileAll } from "@sre/keycloak-provisioning";

/**
 * Reconcile every Agent's dedicated Keycloak workload identity.
 *
 *   config/agents/*.yaml  →  desired Keycloak state  →  Admin REST API
 *
 * This is the CONFIGURATION path. It is a script, not a runtime feature: the
 * request path must never hold Admin API credentials, and check-boundaries
 * fails the build if any code component imports this package.
 *
 * DRY RUN BY DEFAULT. Writing to an identity provider is not something to do as
 * a side effect of running a command, so `--apply` is required.
 *
 * Secrets: the admin credential is read from the environment and never logged,
 * never written to Git, and never returned. Client secrets are generated by
 * Keycloak and stay there — this tool neither reads nor prints one.
 *
 *   KEYCLOAK_URL, KEYCLOAK_REALM, KEYCLOAK_ADMIN, KEYCLOAK_ADMIN_PASSWORD
 *   npm run reconcile:keycloak -- --apply
 */

interface Options {
  apply: boolean;
  baseUrl: string;
  realm: string;
  adminRealm: string;
  username: string;
  password: string;
}

function options(argv: string[], env: NodeJS.ProcessEnv): Options {
  const missing = ["KEYCLOAK_URL", "KEYCLOAK_ADMIN", "KEYCLOAK_ADMIN_PASSWORD"].filter((name) => !env[name]);
  if (missing.length > 0) throw new Error(`missing required environment: ${missing.join(", ")}`);
  return {
    apply: argv.includes("--apply"),
    baseUrl: (env.KEYCLOAK_URL as string).replace(/\/$/u, ""),
    realm: env.KEYCLOAK_REALM ?? "sre-test",
    adminRealm: env.KEYCLOAK_ADMIN_REALM ?? "master",
    username: env.KEYCLOAK_ADMIN as string,
    password: env.KEYCLOAK_ADMIN_PASSWORD as string,
  };
}

/**
 * Fetches a fresh admin token per call rather than holding one. Admin tokens are
 * short-lived, and a reconcile of many clients can outlive one.
 */
function adminToken(config: Options): () => Promise<string> {
  return async () => {
    const response = await fetch(`${config.baseUrl}/realms/${config.adminRealm}/protocol/openid-connect/token`, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({ grant_type: "password", client_id: "admin-cli", username: config.username, password: config.password }),
      signal: AbortSignal.timeout(10_000),
    });
    // never echo the body: a failed admin auth response can carry policy detail
    if (!response.ok) throw new Error(`Keycloak admin authentication failed (${response.status})`);
    const payload = (await response.json()) as { access_token?: string };
    if (!payload.access_token) throw new Error("Keycloak admin authentication returned no token");
    return payload.access_token;
  };
}

const config = options(process.argv.slice(2), process.env);
const registry = loadAgentRegistry(CONFIG_PATHS);
const desired = desiredClientsFor(registry.listSpecialists());

console.log(`${config.apply ? "applying" : "dry run"} · ${desired.length} workload identit${desired.length === 1 ? "y" : "ies"} · realm ${config.realm} @ ${config.baseUrl}`);

const admin = new HttpKeycloakAdmin({ baseUrl: config.baseUrl, realm: config.realm, accessToken: adminToken(config) });
const results = await reconcileAll(admin, desired, { dryRun: !config.apply });

let failed = 0;
for (const result of results) {
  if ("error" in result) {
    failed += 1;
    console.error(`  ✗ ${result.clientId}: ${result.error}`);
    continue;
  }
  console.log(`  ${result.action === "unchanged" ? "·" : "→"} ${result.clientId}: ${result.action}`);
  for (const change of result.changes) console.log(`      ${change}`);
}

if (failed > 0) {
  console.error(`${failed} identit${failed === 1 ? "y" : "ies"} failed to reconcile`);
  process.exit(1);
}
if (!config.apply) console.log("\nno changes were written — re-run with --apply");
