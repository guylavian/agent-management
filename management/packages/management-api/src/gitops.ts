import { generateAgentChange, type AgentDraft, type GeneratedChange } from "./yaml.ts";

/**
 * GitOps change abstraction (TDD §30).
 *
 * Creating or editing an Agent produces a PROPOSED CHANGE, never a live
 * mutation: the portal validates the draft, renders the canonical file and
 * opens a pull request. Reconciliation of the runtime, Keycloak and ToolHive
 * happens after a human merges it. There is deliberately no deploy path here.
 */

export interface ProposedChange {
  /** branch a reviewer will see */
  branch: string;
  title: string;
  body: string;
  files: Array<{ path: string; content: string }>;
  /** everything this change will cause once merged, for the review summary */
  effects: string[];
}

export interface PullRequestResult {
  url: string;
  number?: number;
  status: "created" | "not-configured";
  reason?: string;
}

/** Opens the pull request. Implementations talk to the Git host; none may push to a default branch. */
export interface GitOpsProvider {
  readonly configured: boolean;
  createPullRequest(change: ProposedChange): Promise<PullRequestResult>;
}

export interface ProposeOptions {
  draft: AgentDraft;
  /** username or subject of the requester, recorded in the PR body for audit */
  requestedBy: string;
  /** true when the agent already exists, so the summary says "update" */
  update?: boolean;
}

export function proposeAgentChange(options: ProposeOptions): { change: ProposedChange; generated: GeneratedChange } {
  const generated = generateAgentChange(options.draft);
  const name = generated.document.metadata.name;
  const spec = generated.document.spec;
  if (spec.type !== "specialist") throw new Error("only specialist agents are proposed by the portal");
  const verb = options.update === true ? "Update" : "Add";

  const effects = [
    `${options.update === true ? "update" : "create"} agents/${name}.yaml (canonical Agent policy)`,
    `Keycloak: reconcile workload client ${spec.identity.clientId} (${spec.lifecycle === "active" ? "enabled" : "disabled"})`,
    ...spec.access.map((entry) => `Keycloak: optional scope sre-toolhive-${entry.mcp} and ${entry.tools.length} tool grant(s) on ${entry.mcp}`),
    `Runtime: allowlist ${spec.access.length} MCP(s), ${spec.access.reduce((total, entry) => total + entry.tools.length, 0)} tool(s)`,
    "Argo CD: sync after merge",
  ];

  const body = [
    `${verb} the \`${name}\` SRE specialist agent.`,
    "",
    `Requested by: ${options.requestedBy}`,
    `Owner: ${generated.document.metadata.owner}`,
    `Lifecycle: ${spec.lifecycle}`,
    `Workload identity: \`${spec.identity.clientId}\``,
    "",
    "## Effective access",
    "",
    ...spec.access.map((entry) => `- \`${entry.mcp}\` (aud \`${entry.audience}\`): ${entry.tools.join(", ")}`),
    "",
    "## What merging this changes",
    "",
    ...effects.map((effect) => `- ${effect}`),
    "",
    "Generated by the Agent Management Portal. No credential is included in this change.",
  ].join("\n");

  return {
    generated,
    change: {
      branch: `agent/${options.update === true ? "update" : "add"}-${name}`,
      title: `${verb} ${name} SRE agent`,
      body,
      files: [{ path: generated.path, content: generated.yaml }],
      effects,
    },
  };
}

/**
 * Used when no Git host is wired. It reports "not-configured" rather than
 * pretending a pull request was opened, so the portal never shows a success
 * state for a change that does not exist.
 */
export class UnconfiguredGitOpsProvider implements GitOpsProvider {
  readonly configured = false;
  async createPullRequest(): Promise<PullRequestResult> {
    return { url: "", status: "not-configured", reason: "no Git provider is configured for this deployment" };
  }
}

export interface GitHubGitOpsSettings {
  apiBaseUrl?: string;
  owner: string;
  repo: string;
  baseBranch: string;
  /** callback so the token is sourced from a secret store and never held in config */
  token: () => Promise<string> | string;
  fetchImplementation?: typeof fetch;
}

/** Opens a pull request against a GitHub-compatible API. Never commits to the base branch. */
export class GitHubGitOpsProvider implements GitOpsProvider {
  readonly configured = true;
  readonly #settings: GitHubGitOpsSettings;
  readonly #fetch: typeof fetch;

  constructor(settings: GitHubGitOpsSettings) {
    this.#settings = settings;
    this.#fetch = settings.fetchImplementation ?? fetch;
  }

  async createPullRequest(change: ProposedChange): Promise<PullRequestResult> {
    const base = this.#settings.apiBaseUrl ?? "https://api.github.com";
    const repo = `${this.#settings.owner}/${this.#settings.repo}`;
    const head = await this.#call(`${base}/repos/${repo}/git/ref/heads/${this.#settings.baseBranch}`) as { object: { sha: string } };
    await this.#call(`${base}/repos/${repo}/git/refs`, "POST", { ref: `refs/heads/${change.branch}`, sha: head.object.sha });
    for (const file of change.files) {
      const existing = await this.#maybe(`${base}/repos/${repo}/contents/${file.path}?ref=${change.branch}`) as { sha?: string } | undefined;
      await this.#call(`${base}/repos/${repo}/contents/${file.path}`, "PUT", {
        message: change.title,
        content: Buffer.from(file.content, "utf8").toString("base64"),
        branch: change.branch,
        ...(existing?.sha ? { sha: existing.sha } : {}),
      });
    }
    const pull = await this.#call(`${base}/repos/${repo}/pulls`, "POST", { title: change.title, body: change.body, head: change.branch, base: this.#settings.baseBranch }) as { html_url: string; number: number };
    return { url: pull.html_url, number: pull.number, status: "created" };
  }

  async #call(url: string, method = "GET", body?: unknown): Promise<unknown> {
    const response = await this.#fetch(url, {
      method,
      headers: { authorization: `Bearer ${await this.#settings.token()}`, accept: "application/vnd.github+json", "content-type": "application/json" },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    if (!response.ok) throw new Error(`git provider ${method} failed with ${response.status}`);
    return response.json();
  }

  async #maybe(url: string): Promise<unknown> {
    try { return await this.#call(url); } catch { return undefined; }
  }
}
